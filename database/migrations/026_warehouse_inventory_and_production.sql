CREATE TABLE IF NOT EXISTS inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_type VARCHAR(12) NOT NULL CHECK (item_type IN ('MATERIAL', 'PRODUCT')),
    item_id BIGINT NOT NULL,
    location VARCHAR(32) NOT NULL CHECK (location IN (
        'RAW_MATERIAL_AVAILABLE', 'PRODUCTION_ALLOCATED', 'FINISHED_WAREHOUSE', 'SELLABLE'
    )),
    scope_id BIGINT REFERENCES production_plans(id) ON DELETE RESTRICT,
    quantity_delta NUMERIC(15,3) NOT NULL,
    quantity_after NUMERIC(15,3) NOT NULL CHECK (quantity_after >= 0),
    movement_type VARCHAR(32) NOT NULL CHECK (movement_type IN (
        'OPENING', 'RAW_MATERIAL_RECEIPT', 'MATERIAL_ISSUE', 'PRODUCTION_CONSUMPTION',
        'MATERIAL_RETURN', 'PRODUCTION_OUTPUT', 'FINISHED_GOODS_TRANSFER',
        'PRODUCT_RECEIPT', 'SELLABLE_ADJUSTMENT', 'SALE_RESERVATION', 'SALE_RELEASE'
    )),
    reference_type VARCHAR(40) NOT NULL,
    reference_id BIGINT NOT NULL,
    actor_id BIGINT REFERENCES customers(customer_id) ON DELETE SET NULL,
    actor_name VARCHAR(150) NOT NULL,
    actor_role VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_inventory_movement_scope CHECK (
        (location = 'PRODUCTION_ALLOCATED' AND item_type = 'MATERIAL' AND scope_id IS NOT NULL)
        OR (location <> 'PRODUCTION_ALLOCATED' AND scope_id IS NULL)
    ),
    CONSTRAINT chk_inventory_movement_item_location CHECK (
        (item_type = 'MATERIAL' AND location IN ('RAW_MATERIAL_AVAILABLE', 'PRODUCTION_ALLOCATED'))
        OR (item_type = 'PRODUCT' AND location IN ('FINISHED_WAREHOUSE', 'SELLABLE'))
    ),
    CONSTRAINT chk_inventory_movement_delta CHECK (quantity_delta <> 0 OR movement_type = 'OPENING')
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_inventory_movement_reference
    ON inventory_movements(movement_type, reference_type, reference_id, item_type, item_id,
                           location, (COALESCE(scope_id, 0)));
CREATE INDEX IF NOT EXISTS idx_inventory_movements_period
    ON inventory_movements(created_at, location, item_type, item_id);
CREATE INDEX IF NOT EXISTS idx_inventory_movements_scope
    ON inventory_movements(scope_id, created_at, item_type, item_id)
    WHERE scope_id IS NOT NULL;

CREATE OR REPLACE FUNCTION reject_inventory_movement_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'inventory_movements is append-only; write a compensating movement instead';
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS trg_inventory_movements_immutable ON inventory_movements;
CREATE TRIGGER trg_inventory_movements_immutable
    BEFORE UPDATE OR DELETE ON inventory_movements
    FOR EACH ROW EXECUTE FUNCTION reject_inventory_movement_mutation();

