CREATE TABLE IF NOT EXISTS raw_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(40) NOT NULL,
    name VARCHAR(150) NOT NULL,
    unit VARCHAR(24) NOT NULL,
    available_quantity NUMERIC(15,3) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT chk_raw_material_available_nonnegative CHECK (available_quantity >= 0),
    CONSTRAINT chk_raw_material_code_nonblank CHECK (length(trim(code)) > 0),
    CONSTRAINT chk_raw_material_name_nonblank CHECK (length(trim(name)) > 0),
    CONSTRAINT chk_raw_material_unit_nonblank CHECK (length(trim(unit)) > 0)
