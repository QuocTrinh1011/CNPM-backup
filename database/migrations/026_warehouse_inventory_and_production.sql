CREATE TABLE IF NOT EXISTS production_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_code VARCHAR(40) NOT NULL UNIQUE,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    recipe_id BIGINT NOT NULL REFERENCES product_recipes(id) ON DELETE RESTRICT,
    target_quantity INTEGER NOT NULL CHECK (target_quantity > 0),
    completed_quantity INTEGER NOT NULL DEFAULT 0 CHECK (completed_quantity >= 0),
    assigned_employee_id BIGINT NOT NULL REFERENCES employee_profiles(employee_id) ON DELETE RESTRICT,
    due_date DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'PLANNED'
        CHECK (status IN ('PLANNED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    note VARCHAR(2000),
    created_by BIGINT REFERENCES customers(customer_id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    closed_at TIMESTAMPTZ,
    CONSTRAINT chk_production_plan_completed_target CHECK (completed_quantity <= target_quantity)
);
CREATE INDEX IF NOT EXISTS idx_production_plans_employee_status_due
    ON production_plans(assigned_employee_id, status, due_date, id);
CREATE INDEX IF NOT EXISTS idx_production_plans_status_created
    ON production_plans(status, created_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS production_plan_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id BIGINT NOT NULL REFERENCES production_plans(id) ON DELETE RESTRICT,
