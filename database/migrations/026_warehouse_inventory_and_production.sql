    required_quantity NUMERIC(15,3) NOT NULL CHECK (required_quantity > 0),
    allocated_quantity NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK (allocated_quantity >= 0),
    consumed_quantity NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK (consumed_quantity >= 0),
    returned_quantity NUMERIC(15,3) NOT NULL DEFAULT 0 CHECK (returned_quantity >= 0),
    CONSTRAINT uq_production_plan_material UNIQUE (plan_id, material_id),
